package com.trust.security.resourceserver;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.util.Iterator;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Verifies that {@code spring-boot-configuration-processor} actually
 * produces usable IDE metadata for this starter's public properties - not
 * just that the JSON exists, but that the properties an application would
 * type in its own {@code application.yml} carry a real type and a non-empty
 * description. A silent regression here (missing processor, dropped
 * Javadoc) would degrade every consuming application's IDE experience
 * without failing anything else in the build.
 */
class ConfigurationMetadataTest {

    private JsonNode properties() throws IOException {
        try (InputStream metadata = getClass().getClassLoader()
                .getResourceAsStream("META-INF/spring-configuration-metadata.json")) {
            assertThat(metadata)
                    .as("META-INF/spring-configuration-metadata.json must be generated by "
                            + "spring-boot-configuration-processor")
                    .isNotNull();
            return new ObjectMapper().readTree(metadata).get("properties");
        }
    }

    private JsonNode property(JsonNode properties, String name) {
        for (Iterator<JsonNode> it = properties.iterator(); it.hasNext(); ) {
            JsonNode property = it.next();
            if (name.equals(property.path("name").asString())) {
                return property;
            }
        }
        throw new AssertionError("Property '" + name + "' not found in the generated metadata");
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenClientIdIsFullyDocumented() throws IOException {
        JsonNode clientId = property(properties(), "trust.security.resource-server.client-id");

        assertThat(clientId.path("type").asString()).isEqualTo("java.lang.String");
        assertThat(clientId.path("description").asString()).isNotBlank();
        assertThat(clientId.has("defaultValue")).as("client-id has no default: it is required").isFalse();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenPublicPathsIsFullyDocumented() throws IOException {
        JsonNode publicPaths = property(properties(), "trust.security.resource-server.public-paths");

        assertThat(publicPaths.path("type").asString()).isEqualTo("java.util.List<java.lang.String>");
        assertThat(publicPaths.path("description").asString()).isNotBlank();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenAuthoritiesMappingsIsFullyDocumented() throws IOException {
        JsonNode mappings = property(properties(), "trust.security.authorities.mappings");

        assertThat(mappings.path("type").asString())
                .isEqualTo("java.util.List<com.trust.security.core.role.AuthorityClaimMapping>");
        assertThat(mappings.path("description").asString()).isNotBlank();
    }
}
