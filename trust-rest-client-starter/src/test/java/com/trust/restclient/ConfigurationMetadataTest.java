package com.trust.restclient;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.util.Iterator;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Verifies that {@code spring-boot-configuration-processor} actually
 * produces usable IDE metadata for this starter's public properties - not
 * just that the JSON exists, but that the property an application would
 * type in its own {@code application.yml} carries a real type, a non-empty
 * description, and the actual default from the code. A silent regression
 * here (missing processor, dropped Javadoc) would degrade every consuming
 * application's IDE experience without failing anything else in the build.
 *
 * <p>Only {@code trust.rest-client.*} properties are covered here - the
 * capabilities this starter still owns (retry, circuit breaker,
 * token-acquisition retry, health). Transport (URL, timeouts, TLS) is native
 * {@code spring.http.serviceclient.*} metadata, generated by Spring Boot
 * itself, not this module.
 */
class ConfigurationMetadataTest {

    private JsonNode properties() throws IOException {
        try (InputStream metadata = getClass().getClassLoader()
                .getResourceAsStream("META-INF/spring-configuration-metadata.json")) {
            assertThat(metadata)
                    .as("META-INF/spring-configuration-metadata.json must be generated by "
                            + "spring-boot-configuration-processor")
                    .isNotNull();
            return new ObjectMapper().readTree(metadata).get("properties");
        }
    }

    private JsonNode property(JsonNode properties, String name) {
        for (Iterator<JsonNode> it = properties.iterator(); it.hasNext(); ) {
            JsonNode property = it.next();
            if (name.equals(property.path("name").asString())) {
                return property;
            }
        }
        throw new AssertionError("Property '" + name + "' not found in the generated metadata");
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenRetryMaxAttemptsHasItsRealDefault() throws IOException {
        JsonNode maxAttempts = property(properties(), "trust.rest-client.retry.max-attempts");

        assertThat(maxAttempts.path("type").asString()).isEqualTo("java.lang.Integer");
        assertThat(maxAttempts.path("description").asString()).isNotBlank();
        assertThat(maxAttempts.path("defaultValue").asInt()).isEqualTo(3);
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenRetryWaitDurationHasItsRealDefault() throws IOException {
        JsonNode waitDuration = property(properties(), "trust.rest-client.retry.wait-duration");

        assertThat(waitDuration.path("type").asString()).isEqualTo("java.time.Duration");
        assertThat(waitDuration.path("description").asString()).isNotBlank();
        assertThat(waitDuration.path("defaultValue").asString()).isEqualTo("200ms");
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenRetryEnabledHasItsRealDefault() throws IOException {
        JsonNode enabled = property(properties(), "trust.rest-client.retry.enabled");

        assertThat(enabled.path("type").asString()).isEqualTo("java.lang.Boolean");
        assertThat(enabled.path("description").asString()).isNotBlank();
        assertThat(enabled.path("defaultValue").asBoolean()).isTrue();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenHealthEnabledHasItsRealDefault() throws IOException {
        JsonNode enabled = property(properties(), "trust.rest-client.health.enabled");

        assertThat(enabled.path("type").asString()).isEqualTo("java.lang.Boolean");
        assertThat(enabled.path("description").asString()).isNotBlank();
        assertThat(enabled.path("defaultValue").asBoolean()).isTrue();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenTokenAcquisitionRetryMaxAttemptsHasItsRealDefault()
            throws IOException {
        JsonNode maxAttempts = property(properties(), "trust.rest-client.token-acquisition-retry.max-attempts");

        assertThat(maxAttempts.path("type").asString()).isEqualTo("java.lang.Integer");
        assertThat(maxAttempts.path("description").asString()).isNotBlank();
        assertThat(maxAttempts.path("defaultValue").asInt()).isEqualTo(3);
    }

    /**
     * {@code retryable-status-codes} defaults to {@code Set.of(502, 503, 504)}
     * in code, but the configuration processor cannot infer a
     * {@code defaultValue} for a collection built from a static factory call
     * - this is exactly the case {@code additional-spring-configuration-metadata.json}
     * exists for (see that file). This test locks the merged result, not
     * just the processor's own output.
     */
    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenRetryableStatusCodesHasItsRealDefault()
            throws IOException {
        JsonNode retryableStatusCodes = property(properties(), "trust.rest-client.retry.retryable-status-codes");

        assertThat(retryableStatusCodes.path("type").asString())
                .isEqualTo("java.util.Set<java.lang.Integer>");
        assertThat(retryableStatusCodes.path("description").asString()).isNotBlank();

        java.util.List<Integer> defaultValue = new java.util.ArrayList<>();
        retryableStatusCodes.path("defaultValue").forEach(node -> defaultValue.add(node.asInt()));
        assertThat(defaultValue).containsExactlyInAnyOrder(502, 503, 504);
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenCircuitBreakerEnabledHasItsRealDefault()
            throws IOException {
        JsonNode enabled = property(properties(), "trust.rest-client.circuit-breaker.enabled");

        assertThat(enabled.path("type").asString()).isEqualTo("java.lang.Boolean");
        assertThat(enabled.path("description").asString()).isNotBlank();
        assertThat(enabled.path("defaultValue").asBoolean()).isTrue();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenFailureRateThresholdHasItsRealDefault()
            throws IOException {
        JsonNode threshold = property(properties(), "trust.rest-client.circuit-breaker.failure-rate-threshold");

        assertThat(threshold.path("type").asString()).isEqualTo("java.lang.Float");
        assertThat(threshold.path("description").asString()).isNotBlank();
        assertThat(threshold.path("defaultValue").asDouble()).isEqualTo(50.0);
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenWaitDurationInOpenStateHasItsRealDefault()
            throws IOException {
        JsonNode waitDuration = property(properties(), "trust.rest-client.circuit-breaker.wait-duration-in-open-state");

        assertThat(waitDuration.path("type").asString()).isEqualTo("java.time.Duration");
        assertThat(waitDuration.path("description").asString()).isNotBlank();
        assertThat(waitDuration.path("defaultValue").asString()).isEqualTo("30s");
    }
}
