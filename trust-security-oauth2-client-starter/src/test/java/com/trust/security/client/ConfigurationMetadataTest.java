package com.trust.security.client;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.util.Iterator;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Verifies that {@code spring-boot-configuration-processor} actually
 * produces usable IDE metadata for this starter's public properties - not
 * just that the JSON exists, but that the properties an application would
 * type in its own {@code application.yml} carry a real type, a non-empty
 * description, and the actual default from the code where one exists. A
 * silent regression here (missing processor, dropped Javadoc) would degrade
 * every consuming application's IDE experience without failing anything
 * else in the build.
 */
class ConfigurationMetadataTest {

    private JsonNode properties() throws IOException {
        try (InputStream metadata = getClass().getClassLoader()
                .getResourceAsStream("META-INF/spring-configuration-metadata.json")) {
            assertThat(metadata)
                    .as("META-INF/spring-configuration-metadata.json must be generated by "
                            + "spring-boot-configuration-processor")
                    .isNotNull();
            return new ObjectMapper().readTree(metadata).get("properties");
        }
    }

    private JsonNode property(JsonNode properties, String name) {
        for (Iterator<JsonNode> it = properties.iterator(); it.hasNext(); ) {
            JsonNode property = it.next();
            if (name.equals(property.path("name").asString())) {
                return property;
            }
        }
        throw new AssertionError("Property '" + name + "' not found in the generated metadata");
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenAllowedOriginsIsFullyDocumented() throws IOException {
        JsonNode allowedOrigins = property(properties(), "trust.security.allowed-origins");

        assertThat(allowedOrigins.path("type").asString()).isEqualTo("java.util.List<java.lang.String>");
        assertThat(allowedOrigins.path("description").asString()).isNotBlank();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenPostLogoutRedirectUriIsFullyDocumented() throws IOException {
        JsonNode postLogoutRedirectUri = property(properties(), "trust.security.post-logout-redirect-uri");

        assertThat(postLogoutRedirectUri.path("type").asString()).isEqualTo("java.lang.String");
        assertThat(postLogoutRedirectUri.path("description").asString()).isNotBlank();
        assertThat(postLogoutRedirectUri.has("defaultValue"))
                .as("post-logout-redirect-uri has no default: it is required")
                .isFalse();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenLogoutPathHasItsRealDefault() throws IOException {
        JsonNode logoutPath = property(properties(), "trust.security.logout-path");

        assertThat(logoutPath.path("type").asString()).isEqualTo("java.lang.String");
        assertThat(logoutPath.path("description").asString()).isNotBlank();
        assertThat(logoutPath.path("defaultValue").asString()).isEqualTo("/logout");
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenAuthoritiesMappingsIsFullyDocumented() throws IOException {
        JsonNode mappings = property(properties(), "trust.security.authorities.mappings");

        assertThat(mappings.path("type").asString())
                .isEqualTo("java.util.List<com.trust.security.core.role.AuthorityClaimMapping>");
        assertThat(mappings.path("description").asString()).isNotBlank();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenCspEnabledHasItsRealDefault() throws IOException {
        JsonNode cspEnabled = property(properties(),
                "trust.security.oauth2-client.headers.content-security-policy.enabled");

        assertThat(cspEnabled.path("type").asString()).isEqualTo("java.lang.Boolean");
        assertThat(cspEnabled.path("description").asString()).isNotBlank();
        assertThat(cspEnabled.path("defaultValue").asBoolean()).isFalse();
    }

    @Test
    void givenTheModuleIsBuilt_whenReadingItsGeneratedMetadata_thenCspPolicyHasItsRealDefault() throws IOException {
        JsonNode cspPolicy = property(properties(),
                "trust.security.oauth2-client.headers.content-security-policy.policy");

        assertThat(cspPolicy.path("type").asString()).isEqualTo("java.lang.String");
        assertThat(cspPolicy.path("description").asString()).isNotBlank();
        assertThat(cspPolicy.path("defaultValue").asString())
                .isEqualTo("default-src 'self'; frame-ancestors 'none'; base-uri 'self'; object-src 'none'");
    }
}
